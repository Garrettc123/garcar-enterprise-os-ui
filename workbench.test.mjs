assert(html.includes('name="robots" content="noindex,nofollow,noarchive"'));
assert(html.includes('id="buyer-authorized"')&&html.includes('id="storage-consent"'));
assert(html.includes('id="approve-draft"')&&html.includes('id="copy-draft" disabled'));
assert(js.includes("w.draft.approvedSnapshot='';")&&js.includes('window.confirm'));
assert(!/fetch\s*\(/.test(js),'Local workbench must have no fetch/network calls');
assert(!/sendMessage|stripe\.com\/v1/i.test(js),'No sender or charge implementation');
