import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseCSV,columnMap,parseTimestamp,classifyRow,priorityRows,csvSerialize,isPaid,escapeHtml} from './workbench.js';
const input='\uFEFFLead ID,Created,First Contact,Last Activity,Email,Status,Value\r\nA-1,2026-11-01 10:00,,,,New,500\r\nA-2,2026-11-12 09:30,2026-11-12 09:50,2026-11-12 09:50,user@example.com,Contacted,750\r\nA-3,,,,,Open,\r\nA-4,2026-11-01 10:00,2026-11-01 14:00,2026-11-01 14:00,,New,\r\n';
const {headers,records}=parseCSV(input),map=columnMap(headers);
assert.equal(records.length,4);assert.equal(map.lead_id,'Lead ID');assert.equal(map.received_at,'Created');
const now=Date.parse('2026-11-12T16:00:00Z');const rows=priorityRows(records,map,{now,sla:60,stall:7});
assert.equal(rows.find(x=>x.leadId==='A-1').label,'sat');
assert.equal(rows.find(x=>x.leadId==='A-3').label,'unknown');
assert.equal(rows.find(x=>x.leadId==='A-4').label,'stalled');
assert.equal(rows.find(x=>x.leadId==='A-2').label,'on_time');
assert.equal(rows.find(x=>x.leadId==='A-1').evidence,'unverified');
assert.equal(rows.find(x=>x.leadId==='A-3').evidence,'missing');
assert.equal(rows.find(x=>x.leadId==='A-1').score,78); // sat=70 + within30days=7 + value=1
assert.equal(parseTimestamp('11/12/2026 09:30'),Date.parse('2026-11-12T09:30:00Z'));
assert.equal(parseTimestamp('02/30/2026'),null);
assert.equal(parseTimestamp('garbled'),null);
assert.equal(parseCSV('id,notes\nA,"Hello, ""world"""').records[0].notes,'Hello, "world"');
assert.throws(()=>parseCSV('id,notes\nA,"missing quote'),/unclosed/);
assert.throws(()=>parseCSV('id,id\nA,B'),/distinct/);
assert.equal(csvSerialize([['=2+2','lead'],['a,b','line\nbreak']]),"'=2+2,lead\r\n\"a,b\",\"line\nbreak\"\r\n");
assert.equal(escapeHtml('<script>'), '&lt;script&gt;');
const payment={payment:{status:'paid',verified:true,reference:'pi_verified_by_operator',date:'2026-11-12',amount:497},quotedPrice:497};
assert.equal(isPaid(payment),true);
assert.equal(isPaid({...payment,payment:{...payment.payment,verified:false}}),false);
assert.equal(isPaid({...payment,payment:{...payment.payment,amount:100}}),false);
